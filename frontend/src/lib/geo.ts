/** 解析 Agent 地图坐标: 手动 geo 优先, 否则按国家质心(NodeGet 地图兜底口径)。 */
export function resolveCoord(
  s: { geo_lat?: number | null; geo_lon?: number | null; country_code?: string },
): [number, number] | null {
  if (s.geo_lat != null && s.geo_lon != null) return [s.geo_lat, s.geo_lon];
  const cc = (s.country_code ?? "").toUpperCase();
  const c = CENTROIDS[cc];
  return c ? [...c] : null;
}
